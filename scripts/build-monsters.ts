/**
 * Convert all monster models in C:\Users\Malish\Downloads\mons into slim,
 * self-contained GLBs in apps/client/public/monsters/<id>.glb and record their
 * bounds & animation names in packages/shared/src/monster-models.ts.
 *
 *   npx tsx scripts/build-monsters.ts [sourceDir]
 */
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";
import { NodeIO, getBounds } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, prune } from "@gltf-transform/functions";

const ROOT = process.cwd();
const SRC = process.argv[2] ?? "C:/Users/Malish/Downloads/mons";
const OUT = join(ROOT, "apps/client/public/monsters");
const TABLE = join(ROOT, "packages/shared/src/monster-models.ts");

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);

function slugify(raw: string): string {
  return raw
    .replace(/_Lite$/i, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d+)/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function collectSources(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    const entries = readdirSync(d).sort();
    for (const e of entries) {
      const p = join(d, e);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(glb|gltf|obj)$/i.test(e)) out.push(p);
    }
  };
  walk(dir);
  return out;
}

async function loadDoc(source: string) {
  if (!source.toLowerCase().endsWith(".obj")) return io.read(source);
  const { default: obj2gltf } = await import("obj2gltf");
  const glb = await obj2gltf(source, { binary: true });
  return io.readBinary(new Uint8Array(glb));
}

if (!existsSync(SRC)) {
  console.error(`Source folder not found: ${SRC}`);
  process.exit(1);
}

const sources = collectSources(SRC);
console.log(`Found ${sources.length} source models in ${SRC}`);

if (existsSync(OUT)) rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const usedIds = new Set<string>();
const table: Record<string, { min: [number, number, number]; max: [number, number, number]; anims: string[] }> = {};
let totalBytes = 0;

for (const src of sources) {
  const stem = basename(src, extname(src));
  const baseId = slugify(stem);
  let id = baseId;
  let n = 2;
  while (usedIds.has(id)) id = `${baseId}-${n++}`;
  usedIds.add(id);

  let doc;
  try {
    doc = await loadDoc(src);
    await doc.transform(dedup(), prune());
  } catch (err) {
    console.warn(`  ✖ ${id} (${src}): ${(err as Error).message}`);
    continue;
  }

  const scene = doc.getRoot().listScenes()[0];
  if (!scene) {
    console.warn(`  ✖ ${id}: no scene`);
    continue;
  }
  const b = getBounds(scene);
  const anims = doc.getRoot().listAnimations().map((a) => a.getName()).filter(Boolean);
  const out = join(OUT, `${id}.glb`);
  const glb = await io.writeBinary(doc);
  writeFileSync(out, glb);
  totalBytes += glb.byteLength;

  const r = (v: number) => Math.round(v * 1000) / 1000;
  table[id] = {
    min: b.min.map(r) as [number, number, number],
    max: b.max.map(r) as [number, number, number],
    anims,
  };
}

const lines = Object.entries(table).map(([id, info]) =>
  `  ${JSON.stringify(id)}: { min: [${info.min.join(", ")}], max: [${info.max.join(", ")}], anims: ${JSON.stringify(info.anims)} },`
);
writeFileSync(
  TABLE,
  `// Generated by \`npx tsx scripts/build-monsters.ts\` — bounds & animations for every monster GLB.
export interface MonsterModelInfo {
  min: [number, number, number];
  max: [number, number, number];
  anims: string[];
}

export const MONSTER_MODELS: Record<string, MonsterModelInfo> = {
${lines.join("\n")}
};
`,
);

console.log(`Built ${Object.keys(table).length}/${sources.length} monster GLBs (${(totalBytes / (1024 * 1024)).toFixed(2)} MB) into apps/client/public/monsters`);
